import React, { useRef, useEffect } from "react";
import { usePluginData } from "@docusaurus/useGlobalData";
import useBaseUrl from "@docusaurus/useBaseUrl";
import SlidevIframe from "../SlidevIframe";
import { PresentationIcon } from "../icons";
import type { PluginData } from "../types";
import { PLUGIN_NAME } from "../types";
import styles from "./styles.module.css";

/** Native Slidev slide dimensions (16:9) */
const SLIDE_W = 960;

function normalizePath(url: string): string {
  let normalized = url.endsWith("/") ? url.slice(0, -1) : url;
  if (!normalized.startsWith("/")) normalized = "/" + normalized;
  return normalized.toLowerCase();
}

interface Props {
  readonly link: string;
  readonly width?: string;
  readonly pluginId?: string;
}

// Generated by GitHub Copilot
export default function SlidevLink({ link, width = "550px", pluginId = "default" }: Props) {
  const cardRef = useRef<HTMLDivElement>(null);
  const errorRef = useRef<HTMLDivElement>(null);
  const previewRef = useRef<HTMLDivElement>(null);

  // Set the CSS variable for card width without inline style
  useEffect(() => {
    cardRef.current?.style.setProperty("--slidev-link-width", width);
    errorRef.current?.style.setProperty("--slidev-link-width", width);
  }, [width]);

  useEffect(() => {
    if (!previewRef.current) return;
    const observer = new ResizeObserver(([entry]) => {
      const computedScale = entry.contentRect.width / SLIDE_W;
      previewRef.current?.style.setProperty("--preview-scale", String(computedScale));
    });
    observer.observe(previewRef.current);
    return () => observer.disconnect();
  }, []);

  // Hook must be called directly in the component, never inside a helper function
  const data = usePluginData(PLUGIN_NAME, pluginId) as PluginData;
  // `link` is written without the site's baseUrl (e.g. "/slidev/intro"), while
  // presentation URLs include it. useBaseUrl is idempotent for already-prefixed links.
  const normalizedLink = normalizePath(useBaseUrl(link));
  const presentation = data?.presentations?.find(
    (p) => normalizePath(p.url) === normalizedLink,
  ) ?? null;

  if (!presentation) {
    return (
      <div className={styles.errorCard} ref={errorRef}>
        <div className={styles.errorPreview}>
          <svg className={styles.errorIcon} viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
            <path d="M12 2C6.48 2 2 6.48 2 12s4.48 10 10 10 10-4.48 10-10S17.52 2 12 2zm1 15h-2v-2h2v2zm0-4h-2V7h2v6z" />
          </svg>
        </div>
        <div className={styles.errorContent}>
          <h4 className={styles.errorTitle}>Presentation Not Found</h4>
          <p className={styles.errorMessage}>
            <code className={styles.errorPath}>{link}</code>
            <br />is not available
          </p>
        </div>
      </div>
    );
  }

  const cardContent = (
    <>
      <div className={styles.preview} ref={previewRef}>
        {presentation.previewUrl ? (
          <SlidevIframe
            src={presentation.previewUrl}
            title={`Preview of ${presentation.title}`}
            className={styles.previewIframe}
            loadingClassName={styles.previewIframeLoading}
            loadedClassName={styles.previewIframeLoaded}
            spinnerContainerClassName={styles.previewLoading}
            spinnerClassName={styles.spinner}
            loading="lazy"
            decorative
            withSpinner
          />
        ) : (
          <PresentationIcon className={styles.previewIcon} width={120} height={67} />
        )}
      </div>
      <div className={styles.content}>
        <div className={styles.header}>
          <h4 className={styles.title}>
            <a
              href={presentation.url}
              target="_blank"
              rel="noopener noreferrer"
              className={styles.cardLink}
            >
              {presentation.title}
            </a>
          </h4>
        </div>
        {presentation.description && (
          <p className={styles.description}>{presentation.description}</p>
        )}
      </div>
    </>
  );

  // "Card link" pattern: the title <a> is stretched over the card (see .cardLink),
  // so the iframe preview is not nested inside an anchor.
  return (
    <div ref={cardRef} className={styles.card}>
      {cardContent}
    </div>
  );
}
